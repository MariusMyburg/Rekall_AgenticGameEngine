namespace Rekall.Age.Rendering;

internal static class RekallAgeBitmapFont
{
    private static readonly IReadOnlyDictionary<char, byte[]> Glyphs = new Dictionary<char, byte[]>
    {
        ['A'] = G("010", "101", "111", "101", "101"), ['B'] = G("110", "101", "110", "101", "110"),
        ['C'] = G("011", "100", "100", "100", "011"), ['D'] = G("110", "101", "101", "101", "110"),
        ['E'] = G("111", "100", "110", "100", "111"), ['F'] = G("111", "100", "110", "100", "100"),
        ['G'] = G("011", "100", "101", "101", "011"), ['H'] = G("101", "101", "111", "101", "101"),
        ['I'] = G("111", "010", "010", "010", "111"), ['J'] = G("001", "001", "001", "101", "010"),
        ['K'] = G("101", "101", "110", "101", "101"), ['L'] = G("100", "100", "100", "100", "111"),
        ['M'] = G("10001", "11011", "10101", "10001", "10001"), ['N'] = G("1001", "1101", "1011", "1001", "1001"),
        ['O'] = G("010", "101", "101", "101", "010"), ['P'] = G("110", "101", "110", "100", "100"),
        ['Q'] = G("010", "101", "101", "011", "001"), ['R'] = G("110", "101", "110", "101", "101"),
        ['S'] = G("011", "100", "010", "001", "110"), ['T'] = G("111", "010", "010", "010", "010"),
        ['U'] = G("101", "101", "101", "101", "111"), ['V'] = G("101", "101", "101", "101", "010"),
        ['W'] = G("10001", "10001", "10101", "11011", "10001"), ['X'] = G("101", "101", "010", "101", "101"),
        ['Y'] = G("101", "101", "010", "010", "010"), ['Z'] = G("111", "001", "010", "100", "111"),
        ['0'] = G("111", "101", "101", "101", "111"), ['1'] = G("010", "110", "010", "010", "111"),
        ['2'] = G("110", "001", "010", "100", "111"), ['3'] = G("110", "001", "010", "001", "110"),
        ['4'] = G("101", "101", "111", "001", "001"), ['5'] = G("111", "100", "110", "001", "110"),
        ['6'] = G("011", "100", "111", "101", "111"), ['7'] = G("111", "001", "010", "010", "010"),
        ['8'] = G("111", "101", "111", "101", "111"), ['9'] = G("111", "101", "111", "001", "110"),
        ['-'] = G("000", "000", "111", "000", "000"), ['_'] = G("000", "000", "000", "000", "111"),
        ['.'] = G("0", "0", "0", "0", "1"), [':'] = G("0", "1", "0", "1", "0"),
        ['!'] = G("1", "1", "1", "0", "1"), ['?'] = G("110", "001", "010", "000", "010")
    };

    public static IReadOnlyList<byte> Rows(char character) =>
        Glyphs.TryGetValue(char.ToUpperInvariant(character), out var rows) ? rows : Array.Empty<byte>();

    public static int Width(char character)
    {
        return char.ToUpperInvariant(character) switch
        {
            'M' or 'W' => 5,
            'N' => 4,
            '.' or ':' or '!' => 1,
            _ => 3
        };
    }

    private static byte[] G(params string[] rows) => rows
        .Select(row => row.Aggregate((byte)0, (value, bit) => (byte)((value << 1) | (bit == '1' ? 1 : 0))))
        .ToArray();
}
